//! Pure-Rust `JSON GENERATE` engine (`Milestone M20`).
//!
//! Supports `COUNT IN`, `NAME OF field IS "alias" | OMITTED`, `SUPPRESS`,
//! `CONVERTING ... TO BOOLEAN`, `JSON-CODE`, `JSON-STATUS`, and fixed-buffer overflow handling.

use coblang_common::{CoblangError, Result};

use crate::types::{
    BufferFit, ByteCount, DataNode, DataNodeKind, JsonBooleanMapping, JsonCode, JsonStatus,
    NameMapping, NameOverride, SuppressRule, ValueCategory, copy_into_cobol_buffer,
    normalize_cobol_number, resolve_name_override, should_suppress_item, trim_trailing_spaces,
};

/// Backslash (`U+005C`).
const CH_BACKSLASH: char = '\u{005C}';
/// Double-quote (`U+0022`).
const CH_DQUOTE: char = '\u{0022}';
/// Backspace (`U+0008`).
const CH_BS: char = '\u{0008}';
/// Horizontal tab (`U+0009`).
const CH_TAB: char = '\u{0009}';
/// Line feed (`U+000A`).
const CH_LF: char = '\u{000A}';
/// Form feed (`U+000C`).
const CH_FF: char = '\u{000C}';
/// Carriage return (`U+000D`).
const CH_CR: char = '\u{000D}';

/// Configuration options for `JSON GENERATE`.
#[derive(Debug, Clone, Default)]
pub struct JsonGenerateOptions {
    /// `NAME OF field IS "alias" | OMITTED` overrides.
    pub name_mappings: Vec<NameMapping>,
    /// `SUPPRESS` field/category predicates.
    pub suppress_rules: Vec<SuppressRule>,
    /// `CONVERTING field TO BOOLEAN` condition mappings.
    pub boolean_mappings: Vec<JsonBooleanMapping>,
}

impl JsonGenerateOptions {
    /// Constructs empty default [`JsonGenerateOptions`].
    #[must_use]
    pub const fn new() -> Self {
        Self {
            name_mappings: Vec::new(),
            suppress_rules: Vec::new(),
            boolean_mappings: Vec::new(),
        }
    }

    /// Appends a [`NameMapping`] (`NAME OF` clause).
    ///
    /// # Arguments
    /// * `mapping` - Field rename or `OMITTED` wrapper rule.
    #[must_use]
    pub fn with_name_mapping(mut self, mapping: NameMapping) -> Self {
        self.name_mappings.push(mapping);
        self
    }

    /// Appends a [`SuppressRule`] (`SUPPRESS` clause).
    ///
    /// # Arguments
    /// * `rule` - Field or category suppression rule.
    #[must_use]
    pub fn with_suppress_rule(mut self, rule: SuppressRule) -> Self {
        self.suppress_rules.push(rule);
        self
    }

    /// Appends a [`JsonBooleanMapping`] (`CONVERTING ... BOOLEAN` clause).
    ///
    /// # Arguments
    /// * `mapping` - Boolean true/false value mapping for a COBOL elementary field.
    #[must_use]
    pub fn with_boolean_mapping(mut self, mapping: JsonBooleanMapping) -> Self {
        self.boolean_mappings.push(mapping);
        self
    }
}

/// Output produced by [`json_generate`] and [`json_generate_into_buffer`].
#[derive(Debug, Clone)]
pub struct JsonGenerateOutcome {
    /// Generated UTF-8 RFC 8259 JSON text.
    pub json: String,
    /// Generated byte/character count (`COUNT IN` target value).
    pub count: ByteCount,
    /// Resulting `JSON-CODE` register (`0` on success, `400` on buffer overflow).
    pub json_code: JsonCode,
    /// Resulting `JSON-STATUS` register (`0` on success, `400` on buffer overflow).
    pub json_status: JsonStatus,
}

/// Generates a UTF-8 RFC 8259 JSON document from a COBOL [`DataNode`] hierarchy.
///
/// # Arguments
/// * `root` - Source COBOL group, table, or elementary [`DataNode`].
/// * `options` - `JSON GENERATE` rename, `OMITTED`, suppression, and boolean options.
///
/// # Errors
/// Returns [`CoblangError::XmlJsonProcess`] if a numeric item contains invalid digits or if
/// `NAME OF ... IS OMITTED` is applied to a non-group child inside a JSON object.
pub fn json_generate(
    root: &DataNode,
    options: &JsonGenerateOptions,
) -> Result<JsonGenerateOutcome> {
    let root_override = resolve_name_override(&options.name_mappings, root.name.as_str());
    let rendered = match root_override {
        Some(NameOverride::Omitted) => render_json_value(root, options, GroupLevel::TopUnwrapped)?,
        Some(NameOverride::Rename(alias)) => render_wrapped_root(alias, root, options)?,
        None => render_wrapped_root(root.name.as_str(), root, options)?,
    };

    let json = rendered.unwrap_or_default();
    let count = ByteCount::new(json.len());
    Ok(JsonGenerateOutcome {
        json,
        count,
        json_code: JsonCode::ZERO,
        json_status: JsonStatus::ZERO,
    })
}

/// Generates JSON into a fixed-length COBOL destination byte slice, leaving trailing bytes
/// untouched and setting [`JsonCode::BUFFER_OVERFLOW`] / [`JsonStatus::BUFFER_OVERFLOW`] (`400`)
/// when the destination buffer is smaller than the generated JSON.
///
/// # Arguments
/// * `root` - Source COBOL [`DataNode`].
/// * `options` - `JSON GENERATE` configuration options.
/// * `buffer` - Mutable fixed-length COBOL destination byte slice.
///
/// # Errors
/// Propagates any formatting or schema error from [`json_generate`].
pub fn json_generate_into_buffer(
    root: &DataNode,
    options: &JsonGenerateOptions,
    buffer: &mut [u8],
) -> Result<JsonGenerateOutcome> {
    let mut outcome = json_generate(root, options)?;
    let (written, fit) = copy_into_cobol_buffer(&outcome.json, buffer);
    outcome.count = written;
    if fit == BufferFit::Overflowed {
        outcome.json_code = JsonCode::BUFFER_OVERFLOW;
        outcome.json_status = JsonStatus::BUFFER_OVERFLOW;
    }
    Ok(outcome)
}

/// Distinguishes unwrapped root group rendering from nested subordinate groups.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum GroupLevel {
    /// Top-level unwrapped group (`{}` preserved even when all children are suppressed).
    TopUnwrapped,
    /// Wrapped or subordinate group (omitted when non-empty children are all suppressed).
    Subordinate,
}

/// Renders the outer `{"rootKey": <value>}` wrapper around `root` unless `root` is suppressed.
///
/// # Arguments
/// * `root_key` - Property key for the outer JSON object.
/// * `root` - Root COBOL [`DataNode`].
/// * `options` - Active `JSON GENERATE` options.
fn render_wrapped_root(
    root_key: &str,
    root: &DataNode,
    options: &JsonGenerateOptions,
) -> Result<Option<String>> {
    let Some(inner) = render_json_value(root, options, GroupLevel::Subordinate)? else {
        return Ok(None);
    };
    let mut out = String::with_capacity(root_key.len() + inner.len() + 6);
    out.push('{');
    escape_json_string_into(&mut out, root_key);
    out.push(':');
    out.push_str(&inner);
    out.push('}');
    Ok(Some(out))
}

/// Renders `node` as an unnamed JSON value (`object`, `array`, `string`, `number`, or `boolean`).
///
/// # Arguments
/// * `node` - Source [`DataNode`] to render.
/// * `options` - Active `JSON GENERATE` options.
/// * `level` - Whether `node` is a top-level unwrapped group or subordinate node.
fn render_json_value(
    node: &DataNode,
    options: &JsonGenerateOptions,
    level: GroupLevel,
) -> Result<Option<String>> {
    match &node.kind {
        DataNodeKind::Elementary { category, value } => {
            if should_suppress_item(
                &options.suppress_rules,
                node.name.as_str(),
                Some(*category),
                value,
            ) {
                return Ok(None);
            }
            if let Some(bool_map) =
                find_boolean_mapping(&options.boolean_mappings, node.name.as_str())
            {
                let literal = if bool_map.matches_true(value) {
                    "true"
                } else {
                    "false"
                };
                return Ok(Some(literal.to_owned()));
            }
            match category {
                ValueCategory::Numeric => {
                    let num = normalize_cobol_number("JSON", value)?;
                    Ok(Some(num))
                }
                ValueCategory::Alphanumeric | ValueCategory::National => {
                    let mut s = String::new();
                    escape_json_string_into(&mut s, trim_trailing_spaces(value));
                    Ok(Some(s))
                }
            }
        }
        DataNodeKind::Group { children } => {
            if should_suppress_item(&options.suppress_rules, node.name.as_str(), None, "") {
                return Ok(None);
            }
            let mut members: Vec<String> = Vec::new();
            collect_group_members(children, options, &mut members)?;
            if !children.is_empty() && members.is_empty() && level == GroupLevel::Subordinate {
                return Ok(None);
            }
            let mut obj = String::from("{");
            for (idx, member) in members.iter().enumerate() {
                if idx > 0 {
                    obj.push(',');
                }
                obj.push_str(member);
            }
            obj.push('}');
            Ok(Some(obj))
        }
        DataNodeKind::Table { occurrences } => {
            if should_suppress_item(&options.suppress_rules, node.name.as_str(), None, "") {
                return Ok(None);
            }
            let mut items: Vec<String> = Vec::with_capacity(occurrences.len());
            for occ in occurrences {
                if let Some(elem_json) = render_json_value(occ, options, GroupLevel::Subordinate)? {
                    items.push(elem_json);
                }
            }
            if !occurrences.is_empty() && items.is_empty() && level == GroupLevel::Subordinate {
                return Ok(None);
            }
            let mut arr = String::from("[");
            for (idx, item) in items.iter().enumerate() {
                if idx > 0 {
                    arr.push(',');
                }
                arr.push_str(item);
            }
            arr.push(']');
            Ok(Some(arr))
        }
    }
}

/// Appends `"key":value` member fragments for `children` into `members`, flattening any
/// subordinate group marked `NAME OF group IS OMITTED`.
///
/// # Arguments
/// * `children` - Ordered child nodes of a COBOL group.
/// * `options` - Active `JSON GENERATE` options.
/// * `members` - Output accumulator of rendered `"key":value` strings.
fn collect_group_members(
    children: &[DataNode],
    options: &JsonGenerateOptions,
    members: &mut Vec<String>,
) -> Result<()> {
    for child in children {
        match resolve_name_override(&options.name_mappings, child.name.as_str()) {
            Some(NameOverride::Omitted) => match &child.kind {
                DataNodeKind::Group {
                    children: grand_children,
                } => {
                    if !should_suppress_item(&options.suppress_rules, child.name.as_str(), None, "")
                    {
                        collect_group_members(grand_children, options, members)?;
                    }
                }
                DataNodeKind::Elementary { .. } | DataNodeKind::Table { .. } => {
                    return Err(CoblangError::XmlJsonProcess {
                        kind: "JSON",
                        offset: 0,
                        message: format!(
                            "NAME OF `{}` IS OMITTED inside a group requires a group item",
                            child.name.as_str()
                        ),
                    });
                }
            },
            Some(NameOverride::Rename(alias)) => {
                if let Some(val_json) = render_json_value(child, options, GroupLevel::Subordinate)?
                {
                    members.push(format_member_pair(alias, &val_json));
                }
            }
            None => {
                if let Some(val_json) = render_json_value(child, options, GroupLevel::Subordinate)?
                {
                    members.push(format_member_pair(child.name.as_str(), &val_json));
                }
            }
        }
    }
    Ok(())
}

/// Formats a single `"key":value` JSON object member.
///
/// # Arguments
/// * `key` - Unescaped object property name.
/// * `value_json` - Already-serialized JSON value expression.
fn format_member_pair(key: &str, value_json: &str) -> String {
    let mut member = String::with_capacity(key.len() + value_json.len() + 3);
    escape_json_string_into(&mut member, key);
    member.push(':');
    member.push_str(value_json);
    member
}

/// Finds a [`JsonBooleanMapping`] configured for `field_name`, if any.
///
/// # Arguments
/// * `mappings` - Configured boolean conversion mappings.
/// * `field_name` - Candidate COBOL field name.
fn find_boolean_mapping<'a>(
    mappings: &'a [JsonBooleanMapping],
    field_name: &str,
) -> Option<&'a JsonBooleanMapping> {
    mappings
        .iter()
        .find(|m| m.field_name.as_str() == field_name)
}

/// Appends an RFC 8259 quoted and escaped JSON string literal to `out`.
///
/// # Arguments
/// * `out` - Destination string buffer.
/// * `raw` - Raw UTF-8 string value to quote and escape.
pub fn escape_json_string_into(out: &mut String, raw: &str) {
    out.push(CH_DQUOTE);
    for ch in raw.chars() {
        match ch {
            CH_DQUOTE => {
                out.push(CH_BACKSLASH);
                out.push(CH_DQUOTE);
            }
            CH_BACKSLASH => {
                out.push(CH_BACKSLASH);
                out.push(CH_BACKSLASH);
            }
            CH_BS => {
                out.push(CH_BACKSLASH);
                out.push('b');
            }
            CH_FF => {
                out.push(CH_BACKSLASH);
                out.push('f');
            }
            CH_LF => {
                out.push(CH_BACKSLASH);
                out.push('n');
            }
            CH_CR => {
                out.push(CH_BACKSLASH);
                out.push('r');
            }
            CH_TAB => {
                out.push(CH_BACKSLASH);
                out.push('t');
            }
            ctrl if (ctrl as u32) < 0x20 => {
                let byte = ctrl as u8;
                out.push(CH_BACKSLASH);
                out.push('u');
                out.push('0');
                out.push('0');
                out.push(hex_digit(byte >> 4));
                out.push(hex_digit(byte & 0x0F));
            }
            normal => out.push(normal),
        }
    }
    out.push(CH_DQUOTE);
}

/// Converts a 4-bit nibble (`0..=15`) into its lowercase hexadecimal ASCII `char`.
///
/// # Arguments
/// * `nibble` - Low 4-bit value (`0..=15`).
const fn hex_digit(nibble: u8) -> char {
    if nibble < 10 {
        (b'0' + nibble) as char
    } else {
        (b'a' + (nibble - 10)) as char
    }
}
